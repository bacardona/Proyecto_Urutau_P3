    private static final Color CREAM = new Color(0xF7F3E0);
    private static final Color DARK = new Color(0x2D3A52);

    private final GameWindow window;
    private int selected = 0; // 0 = torre, 1 = pokedex

    public MainMenuForm(GameWindow window) {
        this.window = window;
        applyStyle();
        bindKeys();
        refreshArrow();
    }

    public JPanel getRootPanel() {
        return rootPanel;
    }

    // Colores y fuente estilo juego viejo
    private void applyStyle() {
        rootPanel.setBackground(CREAM);
        rootPanel.setBorder(BorderFactory.createLineBorder(DARK, 8));

        titleLabel.setFont(PixelFont.get(28));
        titleLabel.setForeground(DARK);
        titleLabel.setHorizontalAlignment(SwingConstants.CENTER);

        for (JLabel l : new JLabel[]{towerOption, pokedexOption, arrow1, arrow2}) {
            l.setFont(PixelFont.get(20));
            l.setForeground(DARK);
        }
    }

    // Flechas arriba/abajo y Enter
    private void bindKeys() {
        bind("UP", () -> move(-1));
        bind("DOWN", () -> move(1));
        bind("ENTER", this::choose);
    }

    private void bind(String key, Runnable action) {
        rootPanel.getInputMap(JComponent.WHEN_IN_FOCUSED_WINDOW)
                .put(KeyStroke.getKeyStroke(key), key);
        rootPanel.getActionMap().put(key, new AbstractAction() {
            @Override
            public void actionPerformed(ActionEvent e) {
                action.run();
            }
        });
    }

    private void move(int delta) {
        selected = Math.floorMod(selected + delta, 2);
        refreshArrow();
    }

    // Solo la opción elegida muestra la flecha
    private void refreshArrow() {
        arrow1.setText(selected == 0 ? ">" : " ");
        arrow2.setText(selected == 1 ? ">" : " ");
    }

    private void choose() {
        window.showScreen(selected == 0 ? "tower" : "pokedex");
    }

