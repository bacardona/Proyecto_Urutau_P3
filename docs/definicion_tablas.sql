-- TABLA: ENTRENADOR
CREATE TABLE entrenador (
    id_entrenador NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(40) NOT NULL
);

-- TABLA: JUGADOR
CREATE TABLE jugador (
    id_entrenador     NUMBER(4) PRIMARY KEY,
    batallas_ganadas  NUMBER(4) DEFAULT 0 NOT NULL CHECK (batallas_ganadas >= 0),
    batallas_perdidas NUMBER(4) DEFAULT 0 NOT NULL CHECK (batallas_perdidas >= 0)
);

-- TABLA: MAQUINA
CREATE TABLE maquina (
    id_entrenador NUMBER(4)    PRIMARY KEY,
    rango         VARCHAR2(30) NOT NULL
);

-- TABLA: ATAQUE
CREATE TABLE ataque (
    clase       VARCHAR2(25) NOT NULL CHECK (
        clase IN (
            'DAMAGE','DAMAGE_STATUS','DAMAGE_FLINCH',
            'INFLICT_STATUS','STAT_CHANGE','TWO_TURN'
        )
    ),
    id_ataque   NUMBER(4)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(30)  NOT NULL,
    tipo        VARCHAR2(25)  NOT NULL CHECK (tipo IN (
            'NONE', 'NORMAL', 'FIRE', 'WATER', 'ELECTRIC',
            'GRASS', 'ICE', 'FIGHTING', 'POISON', 'GROUND',
            'FLYING', 'PSYCHIC', 'BUG', 'ROCK', 'GHOST',
            'DRAGON', 'DARK', 'STEEL', 'FAIRY'
        )
    ),
    categoria   VARCHAR2(15)  NOT NULL CHECK (
        categoria IN (
            'PHYSICAL', 'SPECIAL', 'STATUS'
        )
    ),
    dano        NUMBER(3)     DEFAULT 0 NOT NULL CHECK (dano >= 0),
    precision   NUMBER(3)     DEFAULT 100 NOT NULL CHECK (precision BETWEEN 0 AND 100),
    pp          NUMBER(2)     NOT NULL CHECK (pp >= 0),
    prioridad   NUMBER(1)     DEFAULT 0 NOT NULL CHECK (prioridad BETWEEN -7 AND 7)
);



-- TABLA: ATAQUE_PROB_ESTADO
CREATE TABLE ataque_dano_estado (
    id_ataque      NUMBER(4)    PRIMARY KEY,
    estado_alterado VARCHAR2(15) NOT NULL CHECK (
        estado_alterado IN ('PARALYSIS', 'SLEEP', 'POISON', 'BURN', 'FREEZE')
    ),
    probabilidad NUMBER(3) NOT NULL 
    CHECK (probabilidad between 1 and 100)
);

-- TABLA: ATAQUE_CON RETROCESO
CREATE TABLE ataque_dano_retroceso (
    id_ataque           NUMBER(4)    PRIMARY KEY,
    probabilidad NUMBER(3) NOT NULL 
    CHECK (probabilidad between 1 and 100)
);
-- TABLA: ATAQUE_ESTADO
CREATE TABLE ataque_estado (
    id_ataque      NUMBER(4)    PRIMARY KEY,
    tipo_de_estado VARCHAR2(15) NOT NULL CHECK (
        tipo_de_estado IN ('PARALYSIS', 'SLEEP', 'POISON', 'BURN', 'FREEZE')
    )
);

-- TABLA: ATAQUE_ESTADISTICAS
CREATE TABLE ataque_estadisticas (
    id_ataque           NUMBER(4)    PRIMARY KEY,
    tipo_de_estadistica VARCHAR2(20) NOT NULL CHECK (
        tipo_de_estadistica IN (
            'ATTACK', 'DEFENSE', 'SPEED',
            'SPECIAL_ATTACK', 'SPECIAL_DEFENSE', 'ACCURACY'
        )
    ),
    etapa NUMBER(2) NOT NULL CHECK (etapa BETWEEN -6 AND 6),
    objetivo varchar2(15) NOT NULL CHECK (objetivo IN('SELF','OPPONENT'))
);

-- TABLA: DOS_TURNOS
CREATE TABLE ataque_2_turnos (
    id_ataque           NUMBER(4)    PRIMARY KEY,
    mensaje varchar2(60) NOT NULL,
    invulnerable varchar2(10) NOT NULL CHECK (invulnerable IN('true','false'))
);





-- TABLA: POKKEN
CREATE TABLE pokken (
    id_pokken     NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_pokken VARCHAR2(30) UNIQUE NOT NULL,
    hp            NUMBER(4)    NOT NULL CHECK (hp > 0),
    atk           NUMBER(4)    NOT NULL CHECK (atk >= 0),
    def           NUMBER(4)    NOT NULL CHECK (def >= 0),
    atk_sp        NUMBER(4)    NOT NULL CHECK (atk_sp >= 0),
    def_sp        NUMBER(4)    NOT NULL CHECK (def_sp >= 0),
    spd           NUMBER(4)    NOT NULL CHECK (spd >= 0),

    tipo1        VARCHAR2(25)  NOT NULL CHECK (tipo1 IN (
            'NONE', 'NORMAL', 'FIRE', 'WATER', 'ELECTRIC',
            'GRASS', 'ICE', 'FIGHTING', 'POISON', 'GROUND',
            'FLYING', 'PSYCHIC', 'BUG', 'ROCK', 'GHOST',
            'DRAGON', 'DARK', 'STEEL', 'FAIRY'
        )
    ),
    tipo2        VARCHAR2(25) CHECK (tipo2 IN (
            'NONE', 'NORMAL', 'FIRE', 'WATER', 'ELECTRIC',
            'GRASS', 'ICE', 'FIGHTING', 'POISON', 'GROUND',
            'FLYING', 'PSYCHIC', 'BUG', 'ROCK', 'GHOST',
            'DRAGON', 'DARK', 'STEEL', 'FAIRY'
        )
    ),
    
    -- Movimientos (atributos de ataque conservados del pokken original)
    ataque1       NUMBER(4)    NOT NULL,
    ataque2       NUMBER(4),
    ataque3       NUMBER(4),
    ataque4       NUMBER(4),
    -- Reglas de integridad
    CONSTRAINT chk_pokken_tipos_distintos CHECK (tipo2 IS NULL OR tipo1 != tipo2),
    CONSTRAINT chk_pokken_ataques_distintos CHECK (
        (ataque2 IS NULL OR ataque2 != ataque1) AND
        (ataque3 IS NULL OR (ataque3 != ataque1 AND ataque3 != ataque2)) AND
        (ataque4 IS NULL OR (ataque4 != ataque1 AND ataque4 != ataque2 AND ataque4 != ataque3))
    )
);

-- TABLA: COMBATE
CREATE TABLE combate (
    id_combate    NUMBER(6) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_combate DATE      DEFAULT SYSDATE NOT NULL
);

-- TABLA: HISTORIAL_COMBATES (PK COMPUESTA N:M)
CREATE TABLE historial_combates (
    id_entrenador NUMBER(4)    NOT NULL,
    id_combate    NUMBER(6)    NOT NULL,
    resultado     VARCHAR2(10) NOT NULL CHECK (resultado IN ('VICTORIA', 'DERROTA', 'EMPATE')),
    PRIMARY KEY (id_entrenador, id_combate)
);

